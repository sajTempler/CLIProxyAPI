package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/types/descriptorpb"
)

// PrintProto renders a file descriptor as .proto source. The output is for
// reading and diffing; the Go code is generated from the descriptor itself.
func PrintProto(fd *descriptorpb.FileDescriptorProto) string {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/cursor_proto_sync from the Cursor agent CLI bundle. DO NOT EDIT.\n\n")
	b.WriteString("syntax = \"proto3\";\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", fd.GetPackage())
	for _, d := range fd.GetDependency() {
		fmt.Fprintf(&b, "import %q;\n", d)
	}
	if len(fd.GetDependency()) > 0 {
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "option go_package = %q;\n", fd.GetOptions().GetGoPackage())
	for _, e := range fd.GetEnumType() {
		b.WriteString("\n")
		printEnum(&b, e, "")
	}
	for _, m := range fd.GetMessageType() {
		b.WriteString("\n")
		printMessage(&b, m, "")
	}
	return b.String()
}

func printEnum(b *strings.Builder, e *descriptorpb.EnumDescriptorProto, indent string) {
	fmt.Fprintf(b, "%senum %s {\n", indent, e.GetName())
	for _, v := range e.GetValue() {
		fmt.Fprintf(b, "%s  %s = %d;\n", indent, v.GetName(), v.GetNumber())
	}
	fmt.Fprintf(b, "%s}\n", indent)
}

func printMessage(b *strings.Builder, m *descriptorpb.DescriptorProto, indent string) {
	fmt.Fprintf(b, "%smessage %s {\n", indent, m.GetName())
	inner := indent + "  "
	entries := map[string]*descriptorpb.DescriptorProto{}
	for _, n := range m.GetNestedType() {
		if n.GetOptions().GetMapEntry() {
			entries[n.GetName()] = n
			continue
		}
		printMessage(b, n, inner)
	}
	for _, e := range m.GetEnumType() {
		printEnum(b, e, inner)
	}
	printed := map[int32]bool{}
	for _, f := range m.GetField() {
		if f.OneofIndex != nil && !f.GetProto3Optional() {
			idx := f.GetOneofIndex()
			if printed[idx] {
				continue
			}
			printed[idx] = true
			fmt.Fprintf(b, "%soneof %s {\n", inner, m.GetOneofDecl()[idx].GetName())
			for _, g := range m.GetField() {
				if g.OneofIndex != nil && g.GetOneofIndex() == idx && !g.GetProto3Optional() {
					fmt.Fprintf(b, "%s  %s %s = %d;\n", inner, fieldType(g, entries), g.GetName(), g.GetNumber())
				}
			}
			fmt.Fprintf(b, "%s}\n", inner)
			continue
		}
		label := ""
		switch {
		case f.GetProto3Optional():
			label = "optional "
		case f.GetLabel() == descriptorpb.FieldDescriptorProto_LABEL_REPEATED && !isMapField(f, entries):
			label = "repeated "
		}
		fmt.Fprintf(b, "%s%s%s %s = %d;\n", inner, label, fieldType(f, entries), f.GetName(), f.GetNumber())
	}
	fmt.Fprintf(b, "%s}\n", indent)
}

func isMapField(f *descriptorpb.FieldDescriptorProto, entries map[string]*descriptorpb.DescriptorProto) bool {
	if f.GetType() != descriptorpb.FieldDescriptorProto_TYPE_MESSAGE {
		return false
	}
	tn := f.GetTypeName()
	_, ok := entries[tn[strings.LastIndexByte(tn, '.')+1:]]
	return ok
}

func fieldType(f *descriptorpb.FieldDescriptorProto, entries map[string]*descriptorpb.DescriptorProto) string {
	if isMapField(f, entries) {
		tn := f.GetTypeName()
		e := entries[tn[strings.LastIndexByte(tn, '.')+1:]]
		return fmt.Sprintf("map<%s, %s>", fieldType(e.GetField()[0], nil), fieldType(e.GetField()[1], nil))
	}
	switch f.GetType() {
	case descriptorpb.FieldDescriptorProto_TYPE_MESSAGE, descriptorpb.FieldDescriptorProto_TYPE_ENUM:
		return f.GetTypeName()
	default:
		return scalarNames[int(f.GetType())]
	}
}
